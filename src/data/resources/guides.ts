export function getResourceGuide(slug: string): ResourceGuide | undefined {
  return RESOURCE_GUIDES.find((g) => g.slug === slug);
}

export function resourcePath(slug?: string): string {
  return slug ? `/resources/${slug}` : "/resources";
}

