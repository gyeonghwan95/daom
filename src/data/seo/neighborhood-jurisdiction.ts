/** 2026-10-16 2차~4차(키워드 601~2000) 추가분(neighborhood-jurisdiction-ext*.ts) — 같은 경로는 기존 표 아래에 행을 이어 붙인다. */

export function getNeighborhoodTable(
  path: string,
): NeighborhoodTable | undefined {
  const parts = [
    NEIGHBORHOOD_TABLES[path],
    NEIGHBORHOOD_TABLES_EXT[path],
    NEIGHBORHOOD_TABLES_EXT2[path],
    NEIGHBORHOOD_TABLES_EXT3[path],
  ].filter((t): t is NeighborhoodTable => Boolean(t));
  if (!parts.length) return undefined;
  const title = parts.find((t) => t.title)?.title ?? "";
  const note = parts
    .map((t) => t.note)
    .filter(Boolean)
    .join(" ");
  return {
    title,
    rows: parts.flatMap((t) => t.rows),
    ...(note ? { note } : {}),
  };
}
