export function getCorporateContentIntentByKeyword(
  keyword: string,
): CorporateContentIntent | undefined {
  const q = keyword.trim();
  return corporateContentIntents.find(
    (entry) =>
      entry.primaryKeyword === q ||
      entry.secondaryKeywords.includes(q) ||
      entry.naturalAliases.includes(q),
  );
}

export function listCreateNewCorporateIntents(): CorporateContentIntent[] {
  return corporateContentIntents.filter((e) => e.action === "create-new");
}
