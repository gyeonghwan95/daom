/**
 * 캐러셀 대표이미지 manifest — 실제 존재 URL만.
 * 생성물: /images/generated/carousel/<category>/<file>.webp
 * (centered-hook 1200×1200, minimal-type 1200×800)
 * status가 approved|applied 일 때만 metadata·캐러셀·ItemList에 연결된다.
 */

export type CarouselLayoutVariant =
  | "portrait-left"
  | "portrait-right"
  | "portrait-center"
  | "document-focus"
  | "illustration-focus"
  | "lecture-focus"
  | "minimal-type"
  /** 1:1 — 사진 전면 배경 + 가운데 제목. 3:2·3:4로 잘려도 글자가 남는 안전영역 안에 배치 */
  | "centered-hook";

/** centered-hook 썸네일 문구 — title은 페이지 제목이 아니라 클릭을 부르는 짧은 문장 */
export type CarouselThumbnailCopy = {
  eyebrow: string;
  /** 최대 2줄, 줄바꿈은 \n */
  title: string;
  /** 한 줄 */
  subtitle: string;
};

export type CarouselImageStatus =
  | "planned"
  | "generated"
  | "review-required"
  | "approved"
  | "applied";

export type CarouselImageManifestItem = {
  id: string;
  pageUrl: string;
  pageTitle: string;
  pageType: string;
  parentHub?: string;
  primaryKeyword: string;
  secondaryKeywords?: string[];
  /** attorney-photo-inventory id (인물 사용 시) */
  sourcePhotoId?: string;
  /** 인물 외 실사 소스 (public 경로) */
  sourcePhotoPath?: string;
  outputFileName: string;
  outputPath: string;
  width: number;
  height: number;
  headline: string;
  subheadline?: string;
  thumbnail?: CarouselThumbnailCopy;
  layoutVariant: CarouselLayoutVariant;
  visualConcept: string;
  topicIcon?: "family" | "calendar" | "scale" | "building" | "key" | "seal" | "court" | "doc" | "check" | "chart";
  backgroundConcept: string;
  accent: "navy" | "warm" | "sage" | "slate";
  /** sharp resize position 오버라이드 (기본 centre). 얼굴 훼손 방지용 */
  cropPosition?: "centre" | "top" | "bottom" | "left" | "right" | "right top" | "left top";
  alt: string;
  carouselCandidate: boolean;
  ogImageRequired: boolean;
  bodyImageRequired: boolean;
  status: CarouselImageStatus;
};

const SIZES = {
  square: { width: 1200, height: 1200 },
  wide: { width: 1200, height: 800 },
} as const;

function out(category: string, file: string, size: keyof typeof SIZES = "square") {
  return {
    outputFileName: file,
    outputPath: `/images/generated/carousel/${category}/${file}`,
    ...SIZES[size],
  };
}

