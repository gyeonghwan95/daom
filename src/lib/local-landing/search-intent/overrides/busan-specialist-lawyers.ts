export function createSpecialistPage(page: SpecialistPage): SearchIntentContent {
  return {
    slug: page.slug,
    category: "expertise",
    title: page.title,
    metaTitle: page.metaTitle,
    metaDescription: page.metaDescription,
    h1: page.h1,
    eyebrow: page.eyebrow,
    heroParagraphs: page.heroParagraphs,
    summaryBullets: page.summaryBullets,
    primaryKeywords: [page.phrase, ...page.keywords],
    searchIntents: page.whenNeeded,
    whenNeeded: page.whenNeeded,
    documents: page.documents,
    documentsNote: page.documentsNote,
    procedures: page.procedures,
    commonMistakes: page.mistakes,
    proseSections: page.sections.map((section) => ({
      id: section.title.replace(/\s+/g, "-"),
      title: section.title,
      paragraphs: section.paragraphs.filter(Boolean) as string[],
    })),
    faqs: page.faqs,
    relatedCaseLinks: [],
    relatedServiceLinks: page.relatedServiceLinks,
    relatedGuideLinks: [
      { href: "/부산법무사", label: "부산 법무사 종합 안내" },
      { href: "/contact/inquiry", label: "전화·카카오톡·예약 방문 상담" },
    ],
    bottomCtaText: page.bottomCtaText,
    serviceSlug: page.serviceSlug,
  };
}

