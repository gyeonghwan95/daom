const IDENTITY_LOCKED_SLUGS = new Set([
  "해운대법무사",
  "센텀법무사",
  "재송동법무사",
]);

export function isRegionHubIdentityLocked(slug: string): boolean {
  return IDENTITY_LOCKED_SLUGS.has(slug);
}

/** buildMetaDescription이 접미사를 붙이지 않도록 80–120자로 맞춘다. */
export function fitRegionHubDescription(text: string): string {
  const trimmed = text.trim().replace(/\s+/g, " ");
  if (trimmed.length >= 80 && trimmed.length <= 120) return trimmed;
  if (trimmed.length > 120) return `${trimmed.slice(0, 117)}…`;
  const extra = " 해운대 센텀에서 전화·카카오톡·예약 상담합니다.";
  const combined = `${trimmed}${extra}`;
  return combined.length <= 120 ? combined : combined.slice(0, 120);
}

export function getRegionHubCoverage(
  slug: string,
): RegionHubCoverage | undefined {
  return REGION_HUB_COVERAGE[slug];
}

export function neighborhoodSlugToLabel(slug: string): string {
  const name = slug.replace(/법무사$/, "");
  return `${name} 법무사`;
}
