export function photoDesc(photo) {
  const key = decodeURIComponent(photo).replace(/^\/image\//, "");
  if (D[key]) return D[key];
  const m = key.match(/(?:구청_|썸네일[-_])(.+?(?:구청|군청))\.jpg$/);
  if (m) return `${m[1]} 청사 전경`;
  if (/^강의-/.test(key)) return "법률 강의 현장의 안윤정 법무사";
  return "다옴법무사사무소 업무 사진";
}

/** "제목 — 장면" */
export function altFor(title, photo) {
  return `${title.replace(/\n/g, " ")} — ${photoDesc(photo)}`;
}
